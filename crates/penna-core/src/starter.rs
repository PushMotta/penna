//! The configuration `pennad` writes on its first start, when `/etc/penna/config.toml` doesn't exist yet (DESIGN.md §7.5).
//!
//! It has curves for what this machine has, so the studio has something to offer, and three profiles that assign nothing. It
//! starts in the built-in Defaults profile (§4.7): the firmware keeps every fan until a person fills a profile and chooses it.
use crate::config::{Config, ControlConfig, Curve, CurveKind, HysteresisDirection};
use crate::{ControlKind, Inventory, Key, Source};
use std::collections::BTreeMap;

pub const HEADER: &str = "# Penna's configuration, generated by pennad on its first start (DESIGN.md §7.5). It has curves for what this\n\
                          # machine has and profiles that assign nothing yet, and it starts in Defaults: every fan stays with its\n\
                          # BIOS or driver until you adopt it in the studio, which edits this file. To edit it by hand, stop\n\
                          # pennad first, then run `penna check`.\n";

pub const PROFILES: [&str; 3] = ["quiet", "balanced", "render"];

/// The GPU curve of the M4 desk config: below 30 % the driver's own curve takes over and can stop the fans (§4.5).
const GPU_POINTS: [[f64; 2]; 5] = [[45.0, 0.0], [55.0, 35.0], [68.0, 55.0], [78.0, 80.0], [85.0, 100.0]];
const CPU_POINTS: [[f64; 2]; 4] = [[45.0, 30.0], [65.0, 40.0], [78.0, 65.0], [88.0, 100.0]];

/// A starter for this machine: a `gpu` graph per NVIDIA GPU, `cpu-quiet` on the CPU's control temperature when there is one,
/// NVIDIA fans named and allowed to stop (so adopting one keeps the card's zero-RPM mode), and empty profiles.
pub fn starter(inventory: &Inventory) -> Config {
    let gpus: Vec<_> = inventory.devices.iter().filter(|d| d.source == Source::Nvml).collect();
    let mut curves = Vec::new();
    let mut controls = Vec::new();
    for (i, gpu) in gpus.iter().enumerate() {
        let n = if gpus.len() > 1 { format!(" {}", i + 1) } else { String::new() };
        if let Some(temp) = gpu.sensors.iter().find(|s| s.key.channel() == "temp") {
            curves.push(Curve {
                id: if i == 0 { "gpu".to_owned() } else { format!("gpu-{}", i + 1) },
                label: Some(format!("GPU{n}")),
                kind: CurveKind::Graph { source: temp.key.clone(), points: GPU_POINTS.to_vec() },
                response: Some(2.0),
                hysteresis: Some(2.0),
                hysteresis_direction: HysteresisDirection::Falling,
            });
        }
        for c in gpu.controls.iter().filter(|c| matches!(c.kind, ControlKind::Nvml { .. })) {
            let fan = c.key.channel().strip_prefix("fan").and_then(|f| f.parse::<u32>().ok()).unwrap_or(0);
            controls.push(ControlConfig {
                label: Some(format!("GPU{n} fan {}", fan + 1)),
                may_stop: true,
                ..ControlConfig::defaults(c.key.clone())
            });
        }
    }
    if let Some(cpu) = cpu_control_temperature(inventory) {
        curves.push(Curve {
            id: "cpu-quiet".to_owned(),
            label: Some("CPU quiet".to_owned()),
            kind: CurveKind::Graph { source: cpu, points: CPU_POINTS.to_vec() },
            response: Some(5.0),
            hysteresis: Some(3.0),
            hysteresis_direction: HysteresisDirection::Falling,
        });
    }
    Config {
        version: crate::config::VERSION,
        profile: crate::config::DEFAULTS.to_owned(),
        sensors: Vec::new(),
        curves,
        controls,
        profiles: PROFILES.iter().map(|p| ((*p).to_owned(), BTreeMap::new())).collect(),
        labels: BTreeMap::new(),
    }
}

/// AMD's `Tctl` (k10temp), or Intel's package temperature (coretemp).
fn cpu_control_temperature(inventory: &Inventory) -> Option<Key> {
    let find = |driver: &str, label: &dyn Fn(&str) -> bool| {
        inventory
            .devices
            .iter()
            .filter(|d| d.source == Source::Hwmon && d.driver == driver)
            .flat_map(|d| &d.sensors)
            .find(|s| label(&s.label) && !s.below_ambient)
            .map(|s| s.key.clone())
    };
    find("k10temp", &|l| l == "Tctl").or_else(|| find("coretemp", &|l| l.starts_with("Package")))
}

/// The file pennad writes: the header, then the configuration.
pub fn text(config: &Config) -> String {
    format!("{HEADER}{}", config.to_toml())
}

/// One line for the log: what the starter holds.
pub fn summary(config: &Config) -> String {
    let curves: Vec<&str> = config.curves.iter().map(|c| c.id.as_str()).collect();
    format!(
        "curves {}; profiles {}, which assign nothing: every fan stays with its firmware until you adopt it in the studio",
        if curves.is_empty() { "none (nothing on this machine to read a curve from)".to_owned() } else { curves.join(", ") },
        PROFILES.join(", ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{ControlInfo, Device, SensorInfo};

    fn sensor(key: Key, label: &str) -> SensorInfo {
        SensorInfo { key, label: label.into(), limits: vec![], ignored_limits: vec![], below_ambient: false }
    }

    fn device(id: &str, source: Source, driver: &str, sensors: Vec<SensorInfo>, controls: Vec<ControlInfo>) -> Device {
        Device {
            id: id.into(),
            source,
            driver: driver.into(),
            label: driver.into(),
            location: String::new(),
            model: None,
            sensors,
            tachs: vec![],
            controls,
        }
    }

    fn gpu(uuid: &str) -> Device {
        let fans = (0..2)
            .map(|f| ControlInfo {
                key: Key::nvml_fan(uuid, f),
                label: format!("Fan {}", f + 1),
                kind: ControlKind::Nvml { min: 30, max: 100 },
            })
            .collect();
        device(&format!("nvml/{uuid}"), Source::Nvml, "nvml", vec![sensor(Key::nvml_temp(uuid), "GPU")], fans)
    }

    #[test]
    fn one_gpu_and_an_amd_cpu() {
        let cpu = Key::hwmon("k10temp", "0000:00:18.3", "temp1");
        let inv = Inventory {
            devices: vec![
                device("hwmon/k10temp/0000:00:18.3", Source::Hwmon, "k10temp", vec![sensor(cpu.clone(), "Tctl")], vec![]),
                gpu("GPU-1"),
            ],
            ..Inventory::default()
        };
        let c = starter(&inv);
        assert!(c.validate().is_empty(), "{:?}", c.validate());
        assert_eq!(c.curves.iter().map(|c| c.id.as_str()).collect::<Vec<_>>(), ["gpu", "cpu-quiet"]);
        assert_eq!(c.curves[1].kind.source(), Some(&cpu));
        assert_eq!(c.profile, "defaults", "a new install starts in Defaults (§4.7)");
        assert!(c.profiles.values().all(BTreeMap::is_empty), "nothing is adopted");
        assert_eq!(c.controls.len(), 2);
        assert!(c.controls.iter().all(|k| k.may_stop), "adopting a GPU fan keeps zero RPM");
        assert_eq!(c.controls[1].label.as_deref(), Some("GPU fan 2"));
        let back = Config::parse(&text(&c)).expect("the starter reads back");
        assert_eq!(back, c);
    }

    #[test]
    fn two_gpus_and_an_intel_cpu() {
        let pkg = Key::hwmon("coretemp", "coretemp.0", "temp1");
        let inv = Inventory {
            devices: vec![
                device("hwmon/coretemp/coretemp.0", Source::Hwmon, "coretemp", vec![sensor(pkg, "Package id 0")], vec![]),
                gpu("GPU-1"),
                gpu("GPU-2"),
            ],
            ..Inventory::default()
        };
        let c = starter(&inv);
        assert!(c.validate().is_empty());
        assert_eq!(c.curves.iter().map(|c| c.id.as_str()).collect::<Vec<_>>(), ["gpu", "gpu-2", "cpu-quiet"]);
        assert_eq!(c.curves[1].label.as_deref(), Some("GPU 2"));
        assert_eq!(c.controls[3].label.as_deref(), Some("GPU 2 fan 2"));
    }

    #[test]
    fn a_machine_with_nothing_still_gets_valid_profiles() {
        let c = starter(&Inventory::default());
        assert!(c.validate().is_empty());
        assert!(c.curves.is_empty());
        assert_eq!(c.profiles.keys().collect::<Vec<_>>(), ["balanced", "quiet", "render"]);
        assert!(summary(&c).starts_with("curves none"));
    }
}
